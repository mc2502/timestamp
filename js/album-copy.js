const choices = new Map();
let choiceDay = '';

export function albumCaption(meal, done, day) {
  if (choiceDay !== day) {
    choices.clear();
    choiceDay = day;
  }
  const group = ALBUM_CAPTIONS[meal] || ALBUM_CAPTIONS.snack;
  const status = done ? 'saved' : 'pending';
  const key = `${meal}:${status}`;
  if (choices.has(key)) return choices.get(key);
  const storageKey = `timestamp:album-caption:${key}`;
  let previous = '';
  try { previous = localStorage.getItem(storageKey) || ''; } catch { /* 비공개 모드도 표시 */ }
  const pool = group[status].filter((text) => text !== previous);
  const text = pool[Math.floor(Math.random() * pool.length)];
  choices.set(key, text);
  try { localStorage.setItem(storageKey, text); } catch { /* 다음 실행의 중복 방지만 생략 */ }
  return text;
}
